    /**
     * Lists the first names agreeing with the given gender.
     *
     * @param Gender $gender
     * @return list<string>
     */
    public static function firstNames(Gender $gender): array
    {
        if ($gender->isFemale()) {
            return self::FEMALE_NAMES;
        }

        return array_keys(self::MALE_NAMES);
    }

    /**
     * Lists the patronymics a child of the given gender can carry.
     *
     * @param Gender $gender
     * @return list<string>
     */
    public static function patronymics(Gender $gender): array
    {
        return array_column(self::MALE_NAMES, $gender->value);
    }

    /**
     * Lists the last names in the form the given gender carries.
     *
     * @param Gender $gender
     * @return list<string>
     */
    public static function lastNames(Gender $gender): array
    {
        if ($gender->isFemale()) {
            return array_values(self::LAST_NAMES);
        }

        return array_keys(self::LAST_NAMES);
    }
